# --- UI NAVIGATION ---
with open(os.path.join(base_dir, "ui/navigation/NavGraph.kt"), "w") as f:
    f.write("""package com.onndetect.ui.navigation

import androidx.compose.runtime.Composable
import androidx.navigation.NavHostController
import androidx.navigation.compose.NavHost
import androidx.navigation.compose.composable
import com.onndetect.ui.screens.home.HomeScreen
import com.onndetect.ui.screens.scanner.ScannerScreen
import com.onndetect.ui.screens.result.ResultScreen
import com.onndetect.ui.screens.history.HistoryScreen

@Composable
fun ONNNavGraph(navController: NavHostController) {
    NavHost(navController, startDestination = "home") {
        composable("home") { HomeScreen(navController) }
        composable("scanner/{uri}?mode={mode}") { backStackEntry ->
            val uri = backStackEntry.arguments?.getString("uri")
            val mode = backStackEntry.arguments?.getString("mode")
            ScannerScreen(navController, uri, mode)
        }
        composable("result/{scanId}") { backStackEntry ->
            val scanId = backStackEntry.arguments?.getString("scanId")
            ResultScreen(navController, scanId)
        }
        composable("history") { HistoryScreen(navController) }
    }
}
""")

