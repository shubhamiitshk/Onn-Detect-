"""Static consistency checker for the Android + ML cross-platform contract.
Run from repo root:  python scripts/check_android_consistency.py
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "android" / "app" / "src" / "main"
JAVA = APP / "java"

errors = []
warnings = []

# ---------- collect kotlin files ----------
kt_files = {}
for p in JAVA.rglob("*.kt"):
    kt_files[p] = p.read_text(encoding="utf-8", errors="replace")

print(f"Kotlin sources found: {len(kt_files)}")

# class/interface/object/enum declarations + top-level functions per file
declared = {}   # simple-name -> path
for p, src in kt_files.items():
    m = re.findall(r"\b(?:class|interface|object|enum class)\s+(\w+)", src)
    funs = re.findall(r"^\s*(?:@[\w.]+(?:\([^\n]*\))?\s+)*(?:(?:private|internal|public|suspend|inline|override|operator|tailrec)\s+)*fun\s+(?:(?:[\w.?<>]+)\.)?(\w+)\s*\(", src, re.M)
    declared[p.stem] = p
    for name in m:
        declared.setdefault(name, p)
    for name in funs:
        declared.setdefault(name, p)

# ---------- package declarations match directories ----------
for p, src in kt_files.items():
    m = re.search(r"^package\s+([\w.]+)", src, re.M)
    expected = ".".join(p.parent.relative_to(JAVA).parts)
    if not m:
        if src.strip():
            errors.append(f"{p}: no package declaration")
    elif m.group(1) != expected:
        errors.append(f"{p}: package '{m.group(1)}' != dir '{expected}'")

# ---------- internal imports resolve ----------
for p, src in kt_files.items():
    for imp in re.findall(r"^import\s+(com\.onndetect\.[\w.*]+)", src, re.M):
        simple = imp.split(".")[-1]
        if simple in ('R', 'BuildConfig') and imp in ('com.onndetect.R', 'com.onndetect.BuildConfig'):
            continue  # generated by AGP; Kotlin compilation verifies these
        if simple == '*':
            directory = JAVA.joinpath(*imp[:-2].split('.'))
            if not directory.is_dir():
                errors.append(f'{p}: wildcard import {imp} does not resolve')
            continue
        if simple not in declared:
            errors.append(f"{p}: import {imp} does not resolve")

# ---------- brace balance ----------
for p, src in kt_files.items():
    depth = 0
    for ch in re.sub(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])\'|//[^\n]*|/\*.*?\*/', "", src, flags=re.S):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth < 0:
                errors.append(f"{p}: unbalanced braces"); break
    else:
        if depth != 0:
            errors.append(f"{p}: unbalanced braces ({depth} open)")

# ---------- references to still-empty source files ----------
empty_kt = [p for p, s in kt_files.items() if not s.strip()]
for p, src in kt_files.items():
    if not src.strip():
        continue
    for q in empty_kt:
        # e.g. "QualityGate(" or ": QualityGate" style usages
        if re.search(rf"\b{q.stem}\s*[(<:.]", src):
            errors.append(f"{p}: references EMPTY class {q.stem}")

# ---------- manifest resources ----------
manifest = (APP / "AndroidManifest.xml").read_text(encoding="utf-8")
res_dir = APP / "res"
def res_exists(res_type: str, name: str) -> bool:
    hits = list(res_dir.rglob(f"*.{ 'xml' if res_type in ('xml','mipmap','drawable','style','string','color') else 'xml'}"))
    for h in hits:
        if h.stem == name and (
            res_type == "xml" and h.parent.name == "xml"
            or res_type == "drawable" and (h.parent.name == "drawable" or "anydpi" in h.parent.name)
            or res_type == "mipmap" and "anydpi" in h.parent.name
            or res_type in ("style",) and h.name in ("themes.xml",)
            or res_type == "string" and h.name == "strings.xml"
            or res_type == "color" and h.name == "colors.xml"
        ):
            return True
    return False

for ref_type, ref_name in re.findall(r"@(\w+)/([\w.]+)", manifest):
    if ref_type == "xml":
        if not res_exists("xml", ref_name):
            errors.append(f"Manifest resource missing: @xml/{ref_name}")
    elif ref_type == "mipmap":
        if not res_exists("mipmap", ref_name):
            errors.append(f"Manifest resource missing: @mipmap/{ref_name}")
    elif ref_type == "style":
        themes = (res_dir / "values" / "themes.xml")
        if not themes.exists() or f'"{ref_name}"' not in themes.read_text(encoding="utf-8"):
            errors.append(f"Manifest style missing: {ref_name}")

# theme referenced by app must exist
themes = (res_dir / "values" / "themes.xml")
if not themes.exists() or '"Theme.OnnDetect"' not in themes.read_text(encoding="utf-8"):
    errors.append("Missing Theme.OnnDetect")

# ---------- cross-platform feature contract ----------
py_fe = ROOT / "ml" / "src" / "meta_classifier" / "feature_extractor.py"
kt_meta = ROOT / "android" / "app" / "src" / "main" / "java" / "com" / "onndetect" / "detection" / "fusion" / "XGBoostMetaClassifier.kt"
if py_fe.exists() and kt_meta.exists():
    py_src = py_fe.read_text(encoding="utf-8")
    kt_src = kt_meta.read_text(encoding="utf-8")
    assignments = [node for node in ast.parse(py_src).body if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'FEATURE_NAMES' for t in node.targets)]
    feats = ast.literal_eval(assignments[0].value) if len(assignments) == 1 else []
    expected_features = ['srm_score', 'fft_score', 'kl_score', 'flatness_score', 'resolution_norm', 'is_compressed', 'semantic_probe_score', 'c2pa_present', 'lip_sync_corr', 'landmark_jitter']
    if feats != expected_features:
        errors.append('Python fusion feature schema/order changed without a mobile contract migration')
    positions = [kt_src.find(f) for f in expected_features]
    doc_ok = all(n >= 0 for n in positions) and positions == sorted(positions)
    print(f"Feature contract: python features={feats}")
    print(f"Kotlin export documents all 10 features in order: {doc_ok}")
    if not doc_ok:
        errors.append('Kotlin fusion source lacks the complete ordered feature contract')
    if "\\n" in kt_src:
        errors.append("Kotlin meta classifier contains literal \\n escapes!")
else:
    errors.append('Missing fusion contract source')

# ---------- shared grayscale convention ----------
# Kl_score and fft_score both enter the fusion vector, so their grayscale
# conversion must be the SAME integer BT.601 truncation. A float-weight form
# (0.299/0.587/0.114) disagrees on ~2e-4 of RGB triples because those constants
# are not exact binary fractions and the double sum lands just below the
# integer. Bitmap cannot be constructed under plain JUnit, so this is a
# source-text guard; it does not certify native bitmap decoding.
GRAY_EXPR_KOTLIN = 'r * 299 + g * 587 + b * 114) / 1000)'
GRAY_EXPR_KL_KOTLIN = 'Color.red(c) * 299 + Color.green(c) * 587 + Color.blue(c) * 114) / 1000)'
GRAY_EXPR_PYTHON = 'rgb[..., 0] * 299 + rgb[..., 1] * 587 + rgb[..., 2] * 114'
_gray_sources = {
    'FFTSpectralAnalyzer.kt': (
        ROOT / "android/app/src/main/java/com/onndetect/detection/visual/FFTSpectralAnalyzer.kt", GRAY_EXPR_KOTLIN),
    'KLCooccurrenceAnalyzer.kt': (
        ROOT / "android/app/src/main/java/com/onndetect/detection/visual/KLCooccurrenceAnalyzer.kt", GRAY_EXPR_KL_KOTLIN),
    'feature_extractor.py': (py_fe, GRAY_EXPR_PYTHON),
}
for label, (path, expression) in _gray_sources.items():
    if not path.exists():
        errors.append(f'Missing grayscale source: {label}')
        continue
    if expression not in path.read_text(encoding='utf-8'):
        errors.append(f'{label} does not use the shared integer BT.601 luma expression')
for bad in ('0.299', '0.587', '0.114'):
    for label in ('FFTSpectralAnalyzer.kt', 'KLCooccurrenceAnalyzer.kt'):
        if bad in _gray_sources[label][0].read_text(encoding='utf-8'):
            errors.append(f'{label} still uses floating-point luma weight {bad}')
print('Grayscale convention: integer BT.601 truncation shared across both platforms')

# ---------- assets sanity ----------
models_dir = APP / "assets" / "models"
const_dir = APP / "assets" / "constants"
zero_assets = [f.name for f in list(models_dir.glob("*")) + list(const_dir.glob("*")) if f.stat().st_size == 0]
if zero_assets:
    errors.append(f"Zero-byte assets: {zero_assets}")
else:
    print("Assets: models + constants all non-empty")

# Fail on content drift, even when the legacy release is only diagnostic.
from verify_android_artifact import verify_asset_bundle
assets = APP / 'assets'
asset_names = {p.relative_to(assets).as_posix() for p in assets.rglob('*') if p.is_file()}
asset_errors, asset_warnings = verify_asset_bundle(lambda path: (assets / path).read_bytes(), asset_names)
errors.extend(asset_errors)
warnings.extend(asset_warnings)
try:
    release = json.loads((assets / 'constants/release_manifest.json').read_text(encoding='utf-8'))
    revision = release.get('fusion_revision')
    compiled_revision = re.search(r'const val RELEASE_ID\s*=\s*"([^"]+)"', kt_meta.read_text(encoding='utf-8'))
    if not compiled_revision or compiled_revision.group(1) != revision:
        errors.append('Compiled fusion RELEASE_ID differs from asset release')
    staged_fusion = assets / 'fusion/XGBoostMetaClassifier.kt'
    if release.get('validated') is True or staged_fusion.exists():
        if not staged_fusion.is_file() or staged_fusion.read_bytes() != kt_meta.read_bytes():
            errors.append('Staged and compiled Kotlin fusion sources differ')
except (ValueError, OSError) as exc:
    errors.append(f'Invalid release source binding: {exc}')

print("\n=== WARNINGS ===" if warnings else "")
for w in warnings:
    print("W:", w)
print("\n=== ERRORS ===" if errors else "\nNo errors found.")
for e in errors:
    print("E:", e)

sys.exit(1 if errors else 0)
