/**
 * Training/serving contract tests for the optional Tier-2 forensic VLM (`Engine D`).
 *
 * The parity fixture is generated by
 * `ml/scripts/train_forensic_vlm_colab_t4.py --export-parity-fixture` and contains UNTRAINED
 * random weights. It verifies the JSON schema and the 13-output projection, not detection quality.
 */
class OnDemandForensicVlmAnalyzerContractTest {

    private val siglip = "siglip_probe_int8.tflite"

    private fun fixtureJson(): String {
        val stream = javaClass.classLoader!!.getResourceAsStream("forensic_vlm_policy_parity_fixture.json")
        assertNotNull("Parity fixture missing from test resources", stream)
        return stream!!.bufferedReader().use { it.readText() }
    }

    private fun engine(): LiteRTInferenceEngine = LiteRTInferenceEngine(object : ModelLoader {
        override fun loadMapped(fileName: String): MappedModel =
            throw UnsupportedOperationException("No models are loaded in contract tests")
    })

    private fun floats(arr: org.json.JSONArray) = FloatArray(arr.length()) { arr.getDouble(it).toFloat() }

    @Test
    fun policyBundleAndHeadProjectionMatchPythonExport() {
        val json = fixtureJson()
        val bundle = OnDemandForensicVlmAnalyzer.PolicyBundle.fromJson(json)
        val head = requireNotNull(bundle.headContract)
        assertEquals(OnDemandForensicVlmAnalyzer.RUBRIC_AXES, head.axes)

        val probe = JSONObject(json).getJSONObject("parity_probe")
        val hLast = floats(probe.getJSONArray("h_last"))
        val expected = probe.getJSONObject("expected_full")

        val pred = OnDemandForensicVlmAnalyzer.projectWithHeadContract(hLast, head)
        assertEquals(expected.getDouble("class_logit").toFloat(), pred.classLogit, 1e-4f)
        assertEquals(expected.getDouble("class_prob").toFloat(), pred.classProb, 1e-4f)
        val expF = floats(expected.getJSONArray("forgery_logits_6d"))
        val expC = floats(expected.getJSONArray("authentic_counter_logits_6d"))
        for (i in 0 until 6) {
            assertEquals("forgery axis $i", expF[i], pred.forgeryLogits6d[i], 1e-4f)
            assertEquals("counter axis $i", expC[i], pred.authenticCounterLogits6d[i], 1e-4f)
        }

        val maskArr = probe.getJSONArray("applicable_mask_6d")
        val mask = BooleanArray(6) { maskArr.getBoolean(it) }
        val masked = OnDemandForensicVlmAnalyzer.projectWithHeadContract(hLast, head, mask)
        val expMasked = probe.getJSONArray("expected_masked_forgery_logits_6d")
        for (i in 0 until 6) {
            if (expMasked.isNull(i)) {
                assertTrue("axis $i must be NaN when masked", masked.forgeryLogits6d[i].isNaN())
            } else {
                assertEquals(expMasked.getDouble(i).toFloat(), masked.forgeryLogits6d[i], 1e-4f)
            }
        }
    }

