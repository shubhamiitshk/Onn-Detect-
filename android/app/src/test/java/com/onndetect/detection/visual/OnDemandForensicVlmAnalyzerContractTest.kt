    @Test
    fun leasedProjectionBlocksSiglipDuringPrefillAndReleasesAfterwards() {
        val eng = engine()
        val bundle = OnDemandForensicVlmAnalyzer.PolicyBundle.fromJson(fixtureJson())
        val hLast = floats(JSONObject(fixtureJson()).getJSONObject("parity_probe").getJSONArray("h_last"))
        var blockedDuringPrefill = false
        val outcome = OnDemandForensicVlmAnalyzer.executeLeasedProjection(
            inferenceEngine = eng,
            policyBundle = bundle,
            fastFusionProb = 0.55f,
            diagnosticOnly = true,
        ) {
            blockedDuringPrefill = eng.isModelBlocked(siglip)
            hLast
        }
        assertTrue("SigLIP must be blocked while the VLM prefill runs", blockedDuringPrefill)
        assertFalse("SigLIP must be unblocked after the lease closes", eng.isModelBlocked(siglip))
        assertEquals("diagnosticOnly must preserve the specialist score", 0.55f, outcome.posteriorProb, 1e-6f)
        assertTrue(outcome.vlmDialecticalProb in 0f..1f)
    }

    @Test
    fun leaseIsReleasedWhenPrefillThrows() {
        val eng = engine()
        val bundle = OnDemandForensicVlmAnalyzer.PolicyBundle.fromJson(fixtureJson())
        val result = runCatching {
            OnDemandForensicVlmAnalyzer.executeLeasedProjection(eng, bundle, fastFusionProb = 0.5f) {
                throw IllegalStateException("prefill failed")
            }
        }
        assertTrue(result.isFailure)
        assertFalse(eng.isModelBlocked(siglip))
        // A fresh lease must be obtainable after the failure.
        eng.acquireExclusiveVlmSession().close()
    }

    @Test
    fun overlappingExclusiveLeasesAreRejected() {
        val eng = engine()
        val first = eng.acquireExclusiveVlmSession()
        try {
            eng.acquireExclusiveVlmSession()
            fail("A second overlapping lease must be rejected")
        } catch (expected: IllegalStateException) {
            // expected
        }
        assertTrue("Rejected second lease must not release the first lease's block", eng.isModelBlocked(siglip))
        first.close()
        assertFalse(eng.isModelBlocked(siglip))
    }

