"""Torchvision-free experiment runner comparing on-device VLM zero-shot probabilities
against frozen vision-tower probes (SigLIP, CLIP, DINOv2) and Onn-Detect's forensic baseline.

Designed to drop directly into the scratch folder or `ml/scripts/` and run without
requiring `torchvision` or `open_clip` (uses `transformers` image processors and vision
models directly). Launders all images to a uniform JPEG format and resolution first so
container/dimension shortcuts cannot inflate AUC.

Usage:
  python llm_signal_experiment.py zs       # Stage 1: Zero-shot SmolVLM-256M & 500M P(yes)
  python llm_signal_experiment.py enc      # Stage 2: Frozen vision encoders (SigLIP, CLIP, DINOv2)
  python llm_signal_experiment.py current  # Stage 3: Current Onn-Detect features on laundered images
  python llm_signal_experiment.py all      # Run all stages sequentially
"""

