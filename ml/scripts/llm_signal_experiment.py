def log(msg: str) -> None:
    stamp = time.strftime("%H:%M:%S")
    print(f"{stamp} | {msg}", flush=True)


def launder_image(img_path: str | Path, max_side: int = LAUNDER_MAX_SIDE,
                  jpeg_quality: int = LAUNDER_JPEG_QUALITY) -> Image.Image:
    """Re-encode every image (real and fake) identically to remove format/size shortcuts."""
    from data.image_frontend import decode_image

    decoded = decode_image(str(img_path)).image
    w, h = decoded.size
    scale = min(1.0, float(max_side) / float(max(w, h)))
    if scale < 1.0:
        new_size = (max(16, int(round(w * scale))), max(16, int(round(h * scale))))
        decoded = decoded.resize(new_size, Image.Resampling.BILINEAR)
    buf = io.BytesIO()
    decoded.convert("RGB").save(buf, format="JPEG", quality=jpeg_quality, optimize=False)
    buf.seek(0)
    laundered = Image.open(buf).convert("RGB")
    laundered.load()
    return laundered


def load_or_init_cache(cache_path: Path) -> dict[str, np.ndarray]:
    if cache_path.exists():
        with np.load(cache_path, allow_pickle=False) as data:
            return {k: data[k] for k in data.files}
    return {}


def save_cache(cache_path: Path, arrays: dict[str, np.ndarray]) -> None:
    tmp_path = cache_path.with_suffix(".tmp.npz")
    np.savez_compressed(tmp_path, **arrays)
    os.replace(tmp_path, cache_path)


def discover_experiment_splits(data_root: Path, max_per_split: int = 400) -> dict[str, list[tuple[Path, int]]]:
    """Load disjoint stacking (for linear probe fit) and test (for evaluation) splits."""
    from data.contracts import IMAGE_EXTS, balanced_subset, discover_samples

    splits = {}
    for split in ("stacking", "fusion_val", "test"):
        split_dir = data_root / split
        if split_dir.is_dir():
            samples = discover_samples(data_root, split, IMAGE_EXTS)
            splits[split] = balanced_subset(samples, max_per_split) if split != "test" else samples
    if "test" not in splits:
        raise FileNotFoundError(f"Could not find 'test' split under {data_root}")
    if "stacking" not in splits:
        # Fallback to val if stacking split is not separately materialized
        splits["stacking"] = balanced_subset(discover_samples(data_root, "val", IMAGE_EXTS), max_per_split)
    return splits


def ensure_laundered_dataset(cache: dict[str, np.ndarray], data_root: Path,
                             launder_dir: Path) -> dict[str, list[tuple[Path, int]]]:
    """Materialize laundered JPEGs on disk so all detectors read identical file bytes."""
    splits = discover_experiment_splits(data_root)
    laundered_splits: dict[str, list[tuple[Path, int]]] = {}

    for split_name, items in splits.items():
        out_items = []
        for src_path, label in items:
            rel = src_path.relative_to(data_root).with_suffix(".jpg")
            dst_path = launder_dir / rel
            if not dst_path.exists():
                dst_path.parent.mkdir(parents=True, exist_ok=True)
                img = launder_image(src_path)
                img.save(dst_path, format="JPEG", quality=LAUNDER_JPEG_QUALITY)
            out_items.append((dst_path, label))
        laundered_splits[split_name] = out_items
        cache[f"y_{split_name}"] = np.asarray([lbl for _, lbl in out_items], dtype=np.int64)
        cache[f"ids_{split_name}"] = np.asarray(
            [p.relative_to(launder_dir).as_posix() for p, _ in out_items]
        )

    save_cache(CACHE_FILE, cache)
    return laundered_splits


def _resolve_yes_no_token_ids(tokenizer) -> tuple[list[int], list[int]]:
    """Find single-token variants of Yes/yes and No/no in the VLM vocabulary."""
    yes_candidates = ["yes", "Yes", "YES", " yes", " Yes", " YES"]
    no_candidates = ["no", "No", "NO", " no", " No", " NO"]
    yes_ids, no_ids = set(), set()
    for s in yes_candidates:
        ids = tokenizer.encode(s, add_special_tokens=False)
        if len(ids) == 1:
            yes_ids.add(ids[0])
    for s in no_candidates:
        ids = tokenizer.encode(s, add_special_tokens=False)
        if len(ids) == 1:
            no_ids.add(ids[0])
    if not yes_ids or not no_ids:
        raise RuntimeError("Could not resolve single-token Yes/No IDs for tokenizer")
    return sorted(yes_ids), sorted(no_ids)


def score_vlm_zero_shot(
    model_key: str,
    model_id: str,
    laundered_splits: dict[str, list[tuple[Path, int]]],
    cache: dict[str, np.ndarray],
    device: torch.device,
) -> None:
    """Compute normalized P(yes) / (P(yes) + P(no)) from first-step next-token logits."""
    from transformers import AutoModelForImageTextToText, AutoProcessor

    log(f"[ZS] Loading {model_key} ({model_id}) on {device}...")
    processor = AutoProcessor.from_pretrained(model_id)
    dtype = torch.float16 if device.type == "cuda" else torch.float32
    model = AutoModelForImageTextToText.from_pretrained(model_id, torch_dtype=dtype).to(device).eval()

    yes_ids, no_ids = _resolve_yes_no_token_ids(processor.tokenizer)

    for split_name in ("stacking", "test"):
        items = laundered_splits[split_name]
        for prompt_key, prompt_text in PROMPTS.items():
            cache_key = f"zs_{model_key}_{prompt_key}_{split_name}"
            if cache_key in cache and len(cache[cache_key]) == len(items):
                log(f"[ZS] Skipping {cache_key} (already cached)")
                continue

            log(f"[ZS] Scoring {cache_key} ({len(items)} images)...")
            scores = np.zeros(len(items), dtype=np.float32)

            for idx, (img_path, _) in enumerate(items):
                img = Image.open(img_path).convert("RGB")
                messages = [
                    {
                        "role": "user",
                        "content": [
                            {"type": "image"},
                            {"type": "text", "text": prompt_text},
                        ],
                    }
                ]
                chat_prompt = processor.apply_chat_template(messages, add_generation_prompt=True)
                inputs = processor(text=chat_prompt, images=[img], return_tensors="pt")
                inputs = {k: v.to(device) for k, v in inputs.items()}

                with torch.no_grad():
                    out = model(**inputs)
                    next_token_logits = out.logits[0, -1, :].float()
                    probs = torch.softmax(next_token_logits, dim=-1)
                    p_yes = float(probs[yes_ids].sum().item())
                    p_no = float(probs[no_ids].sum().item())
                    denom = p_yes + p_no
                    scores[idx] = p_yes / denom if denom > 1e-12 else 0.5

                if (idx + 1) % 50 == 0 or (idx + 1) == len(items):
                    log(f"[ZS] {cache_key}: {idx + 1}/{len(items)}")

            cache[cache_key] = scores
            save_cache(CACHE_FILE, cache)

    # Also extract SmolVLM's internal SigLIP vision tower features before the pixel-shuffle connector!
    if model_key == "smolvlm_256m" and hasattr(model, "model") and hasattr(model.model, "vision_model"):
        vision_tower = model.model.vision_model
        for split_name in ("stacking", "test"):
            emb_key = f"emb_smolvlm_vision_tower_{split_name}"
            items = laundered_splits[split_name]
            if emb_key in cache and len(cache[emb_key]) == len(items):
                continue
            log(f"[ENC] Extracting internal SmolVLM SigLIP vision-tower embeddings for {split_name}...")
            embs = []
            for img_path, _ in items:
                img = Image.open(img_path).convert("RGB").resize((512, 512), Image.Resampling.BILINEAR)
                arr = (np.asarray(img, dtype=np.float32) / 255.0 - 0.5) / 0.5
                pixel_values = torch.from_numpy(arr.transpose(2, 0, 1)).unsqueeze(0).to(device, dtype=dtype)
                with torch.no_grad():
                    v_out = vision_tower(pixel_values=pixel_values)
                    pooled = v_out.last_hidden_state.float().mean(dim=1).cpu().numpy()[0]
                    pooled = pooled / (np.linalg.norm(pooled) + 1e-12)
                    embs.append(pooled.astype(np.float32))
            cache[emb_key] = np.stack(embs)
            save_cache(CACHE_FILE, cache)

    del model
    if device.type == "cuda":
        torch.cuda.empty_cache()


def _preprocess_vision_manual(img: Image.Image, size: int, mean: tuple[float, float, float],
                              std: tuple[float, float, float]) -> torch.Tensor:
    """Pure PIL + NumPy preprocessing fallback so torchvision is never required."""
    resized = img.convert("RGB").resize((size, size), Image.Resampling.BICUBIC)
    arr = np.asarray(resized, dtype=np.float32) / 255.0
    arr = (arr - np.asarray(mean, dtype=np.float32)) / np.asarray(std, dtype=np.float32)
    return torch.from_numpy(arr.transpose(2, 0, 1)).unsqueeze(0)


def extract_frozen_encoder_embeddings(
    laundered_splits: dict[str, list[tuple[Path, int]]],
    cache: dict[str, np.ndarray],
    device: torch.device,
) -> None:
    """Extract L2-normalized embeddings from standalone SigLIP, CLIP, and DINOv2 backbones."""
    from transformers import CLIPVisionModelWithProjection, Dinov2Model, SiglipVisionModel

    specs = [
        ("siglip_b16", VISION_ENCODERS["siglip_b16"], SiglipVisionModel, 512, (0.5, 0.5, 0.5), (0.5, 0.5, 0.5)),
        ("clip_vit_b32", VISION_ENCODERS["clip_vit_b32"], CLIPVisionModelWithProjection, 224,
         (0.48145466, 0.4578275, 0.40821073), (0.26862954, 0.26130258, 0.27577711)),
        ("dinov2_vits14", VISION_ENCODERS["dinov2_vits14"], Dinov2Model, 224,
         (0.485, 0.456, 0.406), (0.229, 0.224, 0.225)),
    ]

    for key, repo_id, cls, img_size, mean, std in specs:
        need_any = any(
            f"emb_{key}_{s}" not in cache or len(cache[f"emb_{key}_{s}"]) != len(laundered_splits[s])
            for s in ("stacking", "test")
        )
        if not need_any:
            log(f"[ENC] Skipping {key} (already cached)")
            continue

        log(f"[ENC] Loading frozen vision encoder {key} ({repo_id})...")
        try:
            model = cls.from_pretrained(repo_id).to(device).eval()
        except Exception as exc:
            log(f"[ENC] Warning: could not load {key} ({exc}); continuing with remaining encoders.")
            continue

        for split_name in ("stacking", "test"):
            emb_key = f"emb_{key}_{split_name}"
            items = laundered_splits[split_name]
            if emb_key in cache and len(cache[emb_key]) == len(items):
                continue

            log(f"[ENC] Extracting {emb_key} ({len(items)} images)...")
            vecs = []
            for img_path, _ in items:
                img = Image.open(img_path).convert("RGB")
                tensor = _preprocess_vision_manual(img, img_size, mean, std).to(device)
                with torch.no_grad():
                    out = model(pixel_values=tensor)
                    if hasattr(out, "image_embeds") and out.image_embeds is not None:
                        vec = out.image_embeds.float().cpu().numpy()[0]
                    elif hasattr(out, "pooler_output") and out.pooler_output is not None:
                        vec = out.pooler_output.float().cpu().numpy()[0]
                    else:
                        vec = out.last_hidden_state.float().mean(dim=1).cpu().numpy()[0]
                    vec = vec / (np.linalg.norm(vec) + 1e-12)
                    vecs.append(vec.astype(np.float32))
            cache[emb_key] = np.stack(vecs)
            save_cache(CACHE_FILE, cache)

        del model
        if device.type == "cuda":
            torch.cuda.empty_cache()


def extract_current_pipeline_features(
    laundered_splits: dict[str, list[tuple[Path, int]]],
    cache: dict[str, np.ndarray],
) -> None:
    """Run Onn-Detect's current SRM TFLite + FFT + KL feature extractor on laundered images."""
    from meta_classifier.feature_extractor import extract_visual_features, load_baseline
    from validate_export import _run_tflite

    tflite_path = REPO_ROOT / "android" / "app" / "src" / "main" / "assets" / "models" / "srm_forensic_cnn_int8.tflite"
    hist_path = REPO_ROOT / "android" / "app" / "src" / "main" / "assets" / "constants" / "natural_diff_histogram.json"
    manifest_path = REPO_ROOT / "android" / "app" / "src" / "main" / "assets" / "constants" / "release_manifest.json"

    input_size = 128
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        input_size = int(manifest["models"]["srm_forensic_cnn_int8.tflite"]["input_shape"][1])

    class QuantizedVisualWrapper(torch.nn.Module):
        def forward(self, x: torch.Tensor) -> torch.Tensor:
            nhwc = np.transpose(x.cpu().numpy(), (0, 2, 3, 1))
            scores = [_run_tflite(str(tflite_path), item[None]) for item in nhwc]
            return torch.tensor(scores, dtype=torch.float32).reshape(-1, 1)

    srm_model = QuantizedVisualWrapper()
    baseline = load_baseline(str(hist_path) if hist_path.exists() else None)

    for split_name in ("stacking", "test"):
        feat_key = f"X_current_{split_name}"
        items = laundered_splits[split_name]
        if feat_key in cache and len(cache[feat_key]) == len(items):
            log(f"[CUR] Skipping {feat_key} (already cached)")
            continue

        log(f"[CUR] Extracting current 10-feature vector on laundered {split_name} ({len(items)} images)...")
        rows = []
        for idx, (img_path, _) in enumerate(items):
            vec = extract_visual_features(
                str(img_path),
                srm_model,
                torch.device("cpu"),
                baseline,
                input_size=input_size,
            )
            rows.append(vec)
            if (idx + 1) % 100 == 0 or (idx + 1) == len(items):
                log(f"[CUR] {feat_key}: {idx + 1}/{len(items)}")

        cache[feat_key] = np.stack(rows).astype(np.float32)
        save_cache(CACHE_FILE, cache)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=["zs", "enc", "current", "all"], help="Experiment stage to run")
    parser.add_argument(
        "--data-root",
        default=str(REPO_ROOT / "datasets" / "openfake_visual"),
        help="Path to prepared visual dataset root containing stacking/val/test splits",
    )
    parser.add_argument(
        "--launder-dir",
        default=str(SCRIPT_DIR / "laundered_512_q85"),
        help="Directory to store uniform laundered JPEG images",
    )
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    args = parser.parse_args()

    data_root = Path(args.data_root).resolve()
    launder_dir = Path(args.launder_dir).resolve()
    device = torch.device(args.device)

    cache = load_or_init_cache(CACHE_FILE)
    laundered_splits = ensure_laundered_dataset(cache, data_root, launder_dir)

    if args.stage in ("zs", "all"):
        for model_key, model_id in VLM_MODELS.items():
            score_vlm_zero_shot(model_key, model_id, laundered_splits, cache, device)

    if args.stage in ("enc", "all"):
        extract_frozen_encoder_embeddings(laundered_splits, cache, device)

    if args.stage in ("current", "all"):
        extract_current_pipeline_features(laundered_splits, cache)

    log(f"Stage '{args.stage}' complete. Cache saved to {CACHE_FILE}")


if __name__ == "__main__":
    main()
