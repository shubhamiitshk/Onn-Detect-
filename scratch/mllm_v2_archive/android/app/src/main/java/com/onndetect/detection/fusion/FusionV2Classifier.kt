 *  [11] mllm_confidence   — MLLM self-confidence (0.0=low, 0.5=medium, 1.0=high)
 *  [12] mllm_anomaly_count— Number of semantic anomalies detected by MLLM
 *  [13] modality_agreement — Cross-model agreement score [0, 1]
