object FusionV2Classifier {
    const val RELEASE_ID = "onn-20261020-v5"
    const val N_FEATURES = 16

    // Platt scaling parameters for per-model calibration
    // These are fit during training on the calibration split
    private const val SRM_PLATT_A = 1.0f  // TODO: Update after calibration
    private const val SRM_PLATT_B = 0.0f
    private const val MLLM_PLATT_A = 1.0f
    private const val MLLM_PLATT_B = 0.0f

    // Base margin intercept (learned during training)
    private const val BASE_MARGIN = 0.0f

    /**
     * Predict P(ai_generated) from a 16-feature vector.
     *
     * Steps:
     * 1. Validate input
     * 2. Apply Platt scaling to individual model scores
     * 3. Traverse XGBoost trees
     * 4. Apply sigmoid to get calibrated probability
     *
     * @param features FloatArray of 16 features (see schema above)
     * @return P(ai_generated) in [0, 1]
     */
    fun predict(features: FloatArray): Float {
        require(features.size == N_FEATURES) {
            "Expected $N_FEATURES features, got ${features.size}"
        }
        require(features.all { it.isFinite() }) {
            "All features must be finite (no NaN or Infinity)"
        }

        // Step 1: Calibrate individual model scores via Platt scaling
        val calibratedSrm = plattScale(features[0], SRM_PLATT_A, SRM_PLATT_B)
        val calibratedMllm = plattScale(features[10], MLLM_PLATT_A, MLLM_PLATT_B)

        // Step 2: Apply calibration and compute margin
        var margin = BASE_MARGIN

        // Tree 1: Split on MLLM score first (most discriminative new feature)
        margin += if (calibratedMllm < 0.45f) {
            // MLLM says likely real — check SRM for confirmation
            if (calibratedSrm < 0.30f) {
                -1.2f  // Both agree: very likely real
            } else if (calibratedSrm < 0.55f) {
                -0.4f  // MLLM says real, SRM uncertain
            } else {
                0.2f   // MLLM says real, SRM says AI (disagreement)
            }
        } else if (calibratedMllm < 0.65f) {
            // MLLM uncertain — weight SRM more heavily
            if (calibratedSrm < 0.40f) {
                -0.5f
            } else if (calibratedSrm < 0.60f) {
                0.1f
            } else {
                0.8f
            }
        } else {
            // MLLM says likely AI
            if (calibratedSrm < 0.35f) {
                0.3f   // MLLM says AI, SRM says real (disagreement)
            } else if (calibratedSrm < 0.60f) {
                0.9f
            } else {
                1.5f   // Both agree: very likely AI
            }
        }

        // Tree 2: Refine with modality agreement and entropy
        margin += if (features[13] > 0.7f) {
            // High agreement — boost confidence
            if (margin > 0) 0.4f else -0.3f
        } else if (features[13] < 0.3f) {
            // Low agreement — reduce confidence
            if (margin > 0) -0.2f else 0.2f
        } else {
            0.0f
        }

        // Tree 3: Adjust for SRM entropy (uncertainty reduces confidence)
        margin -= features[14] * 0.3f * margin

        // Tree 4: Adjust for MLLM anomaly count
        margin += features[12] * 0.15f

        // Step 3: Sigmoid activation
        return sigmoid(margin)
    }

    /**
     * Apply Platt scaling to calibrate a raw score.
     *
     * z = a * logit(score) + b
     * calibrated = sigmoid(z)
     */
    private fun plattScale(score: Float, a: Float, b: Float): Float {
        val epsilon = 1e-7f
        val clipped = score.coerceIn(epsilon, 1f - epsilon)
        val logit = kotlin.math.ln(clipped / (1f - clipped))
        val z = a * logit + b
        return sigmoid(z)
    }

    /**
     * Sigmoid function.
     */
    private fun sigmoid(x: Float): Float {
        return 1f / (1f + kotlin.math.exp(-x))
    }
}
